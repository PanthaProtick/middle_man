// Static, conservative reachability and control ledger. Run from the repo root.
import { readFileSync, readdirSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, relative, dirname, join } from 'node:path';

const root = resolve('frontend/src');
const normalize = path => relative(process.cwd(), path).replaceAll('\\', '/');
const walk = dir => readdirSync(dir, { withFileTypes: true }).flatMap(entry =>
  entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]);
const files = walk(root).filter(file => /\.[jt]sx?$/.test(file));
const modules = new Map();
for (const file of files) {
  const source = readFileSync(file, 'utf8');
  const dependencies = [];
  for (const match of source.matchAll(/\b(?:import|export)\s+(?!type\b)(?:[^;]*?\s+from\s*)?['"](\.[^'"]+)['"]/g)) {
    const base = resolve(dirname(file), match[1]);
    const target = [base + '.ts', base + '.tsx', join(base, 'index.ts'), join(base, 'index.tsx')].find(existsSync);
    if (target?.startsWith(root)) dependencies.push(target);
  }
  modules.set(file, { source, dependencies });
}
const reachable = new Set();
function visit(file) {
  if (reachable.has(file)) return;
  reachable.add(file);
  modules.get(file)?.dependencies.forEach(visit);
}
visit(resolve(root, 'main.tsx'));
const tests = files.filter(file => /\.test\.tsx?$/.test(file));
const groups = [
  ['Entry and work discovery', /(?:^App\.tsx|Root|Header|Session|SignIn|ShopSetup|Workspace|ShopMetrics|OrderList|OrderSearch|OrderDate|OrderWorkQuery|OrderExport|AttentionPreview|PreparationPreview|LocaleSwitch)/],
  ['Create, collect and inspect', /(?:CreateOrder|OrderParcel|OrderCard|OrderDetail|OrderOverview|BuyerLink|BuyerCorrection|BuyerPortal|BuyerOrder|BuyerSubmission|PaymentClaimFields|PathaoLocations|Contact|Address)/],
  ['Payment evidence and decisions', /(?:ManualTransaction|SmsImport|Transaction|PaymentsSection|EvidenceResolution|ReceiptCorrection|PaymentException|OrderPayment|OrderOutcome|PaymentHistory)/],
  ['Delivery, assistance and administration', /./],
];
const rows = [];
for (const file of [...reachable].sort()) {
  const entry = modules.get(file);
  if (!entry || !file.endsWith('.tsx')) continue;
  entry.source.split(/\r?\n/).forEach((text, index) => {
      const tag = text.match(/<(button|input|select|textarea|a|form|summary)\b/)?.[1] ?? 'handler';
      if (tag !== 'handler' || /\bon[A-Z]\w*=/.test(text)) {
        const line = index + 1;
        const expressions = /\bon[A-Z]\w*=/.test(text) ? [text.trim()] : [];
        const group = groups.find(([, pattern]) => pattern.test(file.split(/[\\/]/).at(-1)))[0];
        const proof = tests.filter(test => modules.get(test)?.dependencies.includes(file)).map(normalize);
        rows.push({ file: normalize(file), line, tag, events: expressions, group, proof,
          dependencies: entry.dependencies.map(normalize) });
      }
  });
}
const destination = '.issues/project-revamp/baseline-actions';
mkdirSync(destination, { recursive: true });
const escape = value => value.replaceAll('|', '\\|').replaceAll('`', "'");
for (let start = 0; start < rows.length; start += 90) {
  const batch = rows.slice(start, start + 90);
  const lines = ['# Baseline control ledger — ' + (start / 90 + 1), '',
    'Generated by [inventory.mjs](../baseline-fixture/inventory.mjs).',
    'Read with [trace rules and response/error/test owners](../baseline-action-trace.md).',
    'Each row is a control or handler source line, including native disclosures and inputs.',
    'Static reachability includes conditional branches; it does not assert browser execution.', '',
    '| ID | Source control | Event expression / native behavior | Journey contract group |',
    '| --- | --- | --- | --- |'];
  batch.forEach((row, index) => lines.push(`| ${start + index + 1} | ${row.file}:${row.line} (${row.tag}) | ${escape(row.events.join('; ') || 'Native input, link, form or disclosure; see source attributes')} | ${row.group} |`));
  writeFileSync(`${destination}/${String(start / 90 + 1).padStart(2, '0')}.md`, lines.join('\n') + '\n');
}
writeFileSync('.cache/revamp-baseline/control-inventory.json', JSON.stringify({
  source: '0d2f05857eea9940df13a351e80a80917f512ca6', controls: rows,
  reachable: [...reachable].map(normalize).sort(),
  unreferenced: files.filter(file => !reachable.has(file) && !/test|Test/.test(file)).map(normalize),
}, null, 2));
console.log(`${rows.length} controls in ${new Set(rows.map(row => row.file)).size} reachable component modules; ${reachable.size} source dependencies.`);
